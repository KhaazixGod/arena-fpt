"""E11: sheets of SEEN (train) objects in NEW arrangements, for the sim analogue of G1a (KE_HOACH_HUONG_1.md §5: ACT, train objects, C0/C1).

Same generator as the train/dev sheets (arena.arrangements.generate on the train split), new seeds (demos used 10..13), ids "seen_C*" so they cannot be
mistaken for the demo arrangements.  Out: arrangements/sim_seen/seen_C0.csv, seen_C1.csv.
    env -u PYTHONPATH ~/env_isaac/bin/python scripts/e11_seen_sheets.py
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, HERE)
from arena.arrangements import MARGIN_MM, band_geometry, generate  # noqa: E402
from arena.scene import load_scene_cfg  # noqa: E402

N = 20
SEEDS = {"C0": 40, "C1": 41}
OBJECTS = os.path.join(HERE, "configs", "objects_sim.csv")
OUT = os.path.join(HERE, "arrangements", "sim_seen")

sc = load_scene_cfg()
width, b_left = band_geometry(sc)
os.makedirs(OUT, exist_ok=True)
for level, seed in SEEDS.items():
    rows = generate(f"train_{level}", N, seed, OBJECTS, sc)
    for r in rows:
        r["arrangement_id"] = r["arrangement_id"].replace("train_", "seen_")
    path = os.path.join(OUT, f"seen_{level}.csv")
    with open(path, "w", newline="", encoding="utf-8") as f:
        f.write(f"# arena arrangement sheet seen_{level}: n={N} seed={seed} objects=configs/objects_sim.csv split=train (new arrangements of seen objects, "
                f"scripts/e11_seen_sheets.py); generated by dir1/make_arrangements.place() on a {width:.0f} mm virtual belt = band x "
                f"{sc['belt']['object_band_x_mm']} + {MARGIN_MM:.0f} mm margins (y from its left edge, b = {b_left:.0f} - y)\n")
        w = csv.DictWriter(f, fieldnames=["arrangement_id", "first_method", "idx", "object", "x_mm", "y_mm", "yaw_deg"])
        w.writeheader()
        w.writerows(rows)
    print(f"wrote {path}: {N} arrangements, {len(rows)} objects")
